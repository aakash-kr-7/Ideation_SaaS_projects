import { spawn } from "node:child_process";
import { createServer } from "node:net";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const port = Number(process.env.SHOULDBUILD_E2E_PORT ?? 4317);
if (!Number.isInteger(port) || port < 1024 || port > 65535) throw new Error(`Invalid isolated browser port: ${port}`);
await new Promise((resolve, reject) => {
  const probe = createServer();
  probe.once("error", () => reject(new Error(`Browser harness refused occupied port ${port}; terminate the stale server before release testing.`)));
  probe.listen(port, "127.0.0.1", () => probe.close(resolve));
});
const buildId = `reveal-${new Date().toISOString().replace(/\D/g, "").slice(0, 14)}-${crypto.randomUUID().slice(0, 8)}`;
const artifactDir = path.resolve("artifacts/browser");
await mkdir(artifactDir, { recursive: true });
await writeFile(path.resolve("lib/generated-build-id.ts"), `// Generated by the production browser harness.\nexport const GENERATED_BUILD_ID = ${JSON.stringify(buildId)};\n`);
await new Promise((resolve, reject) => {
  const child = spawn(process.execPath, [path.resolve("node_modules/next/dist/bin/next"), "build"], {
    cwd: process.cwd(),
    env: { ...process.env, NODE_ENV: "production", SHOULDBUILD_DEPLOYMENT_ENV: "local-production-proof" },
    stdio: "inherit",
    windowsHide: true,
  });
  child.once("error", reject);
  child.once("exit", (code, signal) => code === 0 ? resolve() : reject(new Error(`Production build exited with ${code ?? signal}`)));
});
await writeFile(path.join(artifactDir, "expected-build.json"), JSON.stringify({ buildId, port, builtAt: new Date().toISOString() }, null, 2));
